        print(f" 99th Percentile (P99):  {np.percentile(arr, 99):.3f} ms")
        print(f" Min / Max Time:         {np.min(arr):.3f} ms / {np.max(arr):.3f} ms")
        print(f" Max Retina Throughput:  {1000.0 / np.mean(arr):.1f} FPS")
        print(f" Stimulation Vector Dim: {len(out.stimulation_currents)} channels")
        print(f" Spikes Active / Cycle:  {np.sum(out.spikes)} spikes")
        print("-" * 60)
        print(f" [PASS] Retina processing time ({np.mean(arr):.3f} ms) is negligible (< 1 ms),")
        print(" leaving > 38 ms of latency budget for SNN inference!")
